import {spawnSync} from 'node:child_process';
import {writeFile,mkdir} from 'node:fs/promises';
import {resolve,dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const lab=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const [variable,relativeFile]=process.argv.slice(2);
if(!/^__gp[A-Za-z]+Audit$/.test(variable)||!relativeFile)throw Error('Uso: nombre window audit y ruta relativa al laboratorio');
const file=resolve(lab,relativeFile);if(!file.startsWith(lab+'\\')&&!file.startsWith(lab+'/'))throw Error('Fuera del laboratorio');
const run=spawnSync(process.execPath,[join(lab,'tools/browser.mjs'),'eval',`JSON.stringify(window.${variable})`],{encoding:'utf8',windowsHide:true,maxBuffer:2*1024*1024});
if(run.status!==0)throw Error(run.stderr||run.stdout);
const section=run.stdout.match(/### Result\s*\n([^\n]+)(?:\n|$)/);
if(!section)throw Error('CLI no devolvió un resultado JSON: '+run.stdout.slice(0,500));
const value=JSON.parse(section[1]);const data=typeof value==='string'?JSON.parse(value):value;
if(!data||!data.checkedAt)throw Error('No hay auditoría persistida en esta página');
await mkdir(dirname(file),{recursive:true});await writeFile(file,JSON.stringify(data,null,2));
console.log(JSON.stringify({saved:relativeFile,checkedAt:data.checkedAt,cases:data.screens?.length??data.results?.length}));
